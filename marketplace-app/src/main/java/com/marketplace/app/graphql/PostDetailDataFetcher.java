package com.marketplace.app.graphql;

import com.marketplace.app.graphql.generated.DgsConstants;
import com.marketplace.app.graphql.generated.types.NeighborhoodPost;
import com.marketplace.app.graphql.generated.types.PostComment;
import com.marketplace.community.spi.NeighborhoodPostDetailPort;
import com.marketplace.shared.api.NeighborhoodFeedPostView;
import com.marketplace.shared.api.NeighborhoodPostCommentView;
import com.marketplace.shared.api.PagedRequest;
import com.marketplace.shared.api.PagedResponse;
import com.marketplace.shared.security.CurrentUserProvider;
import com.netflix.graphql.dgs.DgsComponent;
import com.netflix.graphql.dgs.DgsQuery;
import com.netflix.graphql.dgs.InputArgument;
import io.github.resilience4j.ratelimiter.annotation.RateLimiter;
import org.springframework.data.domain.OffsetScrollPosition;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.ScrollPosition;
import org.springframework.graphql.data.pagination.EncodingCursorStrategy;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;

import java.util.List;
import java.util.UUID;

/**
 * The composite post/source detail journey's GraphQL adapter (the
 * corrected plan §11-Phase-7 + the journey inventory #599 §5 item 3 +
 * the readiness doc's P0-1 closure — «تفاصيل منشور/مصدر: قراءة مركبة
 * تجمع التفاصيل والتعليقات والوسائط العامة المسموح بها»). The
 * journey-aware composition role the home read established (design §1:
 * compose experiences, never mirror the database or duplicate business
 * rules) — its second real journey: the post detail read.
 *
 * <p><b>The composite lives in the OPERATION DOCUMENT, not in a wrapper
 * type</b> (the {@code HomeDataFetcher} precedent verbatim): the two
 * root fields the detail journey composes in ONE authenticated
 * round-trip (the measured REST comparison the inventory's acceptance
 * gate pins — the same journey over REST is two HTTP requests:
 * {@code GET /api/v1/posts/{postId}} +
 * {@code GET /api/v1/posts/{postId}/comments}, both contracts this
 * wave's P0-1 closure added/owns on the REST side). GraphQL composes at
 * the document level: the client selects both root fields in one
 * operation and pays ONE transport round-trip while each field still
 * delegates to exactly the owning module's declared SPI —
 * selection-driven cost (a post-only document never touches the
 * comments seam, and vice versa — the cost tests pin this). A wrapper
 * type would add nothing the document does not already carry; and a
 * connection-typed field ON the {@code NeighborhoodPost} type would
 * force the build-time codegen to resolve a type it never emits (the
 * connection types are runtime-generated by
 * {@code ConnectionTypeDefinitionConfigurer} — the Phase-1 design),
 * so the feed journey's transport contract stays untouched
 * byte-for-byte and the comments leg rides its own root field.</p>
 *
 * <p><b>One use case, one set of rules — on both legs</b> (the
 * inventory §8: «يجب أن يستدعي REST وGraphQL Use Case واحدًا وقواعد
 * عمل واحدة»): both legs delegate to the community module's declared
 * {@link NeighborhoodPostDetailPort} (the same {@code getPost}/
 * {@code getComments} use cases the REST surface's controller invokes —
 * the post gate's honest 404 for an unknown, hidden or deleted post,
 * the re-validation of the current state at open time the inventory's
 * P0-1 demands, the membership gate in the post's OWN neighborhood, and
 * the comment thread's complete sort key {@code createdAt ASC, id ASC}
 * all stay inside the owner). This adapter owns ZERO domain rules; its
 * only work is identity resolution, the bounded pagination math, and
 * the mapping into the SDL's own generated transport types.</p>
 *
 * <p><b>The field-level denial contract</b> (the nullable envelope the
 * {@code neighborhoodFeed} field measured): both root fields are
 * nullable deliberately — the owner's {@code ResourceNotFoundException}
 * (the honest 404) and {@code AccessDeniedException} (the REST read's
 * own 403) travel the seam and the exception resolver classifies them
 * to the NF-001/AUTHZ taxonomies AT THE FIELD LEVEL: the denied field
 * resolves to null WITH one classified error in {@code errors[]}, while
 * the sibling section of the same document still resolves. The
 * composite never bends the owner's rules and never destroys the
 * sibling section (on a NON-NULL root field a GraphQL field error
 * propagates the null up and destroys the whole composite's data —
 * measured against the GraphQL spec's null propagation; strictly worse
 * than the REST journey it replaces).</p>
 *
 * <p><b>Programming model:</b> DGS — {@code @DgsComponent} +
 * {@code @DgsQuery}/{@code @InputArgument} with the schema-first
 * {@code DgsConstants} field bindings (the Phase-2/3 pattern; an SDL
 * rename or removal fails compilation HERE instead of drifting). The
 * comments connection rides the SAME official pagination path the
 * services and neighborhoodFeed fields measured end to end: the relay
 * {@code first}/{@code after} arguments bind onto this method, the
 * cursor decodes through the injected Boot-configured
 * {@code EncodingCursorStrategy} ({@code ScrollPositionCursorStrategy},
 * base64), the bounded page crosses the framework-neutral port as a
 * {@link PagedRequest}, and the returned {@link Page} is adapted into
 * the {@code PostCommentConnection} envelope by Boot's
 * {@code ConnectionFieldTypeVisitor} through the DGS integration's
 * customizer chain — identical envelope, identical {@code O_<offset>}
 * cursors on the wire, identical bounds logic (default-when-absent,
 * hard-capped, non-positive {@code first} = the relay spec's honest
 * empty page without any owning-module work, misaligned or foreign
 * cursors rejected as validation errors).</p>
 *
 * <p><b>The principal:</b> resolved from the request thread's
 * {@link SecurityContextHolder} — the DGS method-invocation model has
 * no {@code Authentication} parameter resolver (the measured pattern
 * the home and mutation paths ride). The endpoint itself sits behind
 * the resource-server chain's {@code anyRequest().authenticated()}
 * (anonymous never reaches this adapter; the security integration test
 * pins the 401).</p>
 */
@DgsComponent
public class PostDetailDataFetcher {

    private final NeighborhoodPostDetailPort postDetailPort;
    private final CurrentUserProvider currentUserProvider;
    private final NeighborhoodFeedMapper feedMapper;
    private final PostCommentMapper commentMapper;
    private final GraphQlProperties properties;
    private final EncodingCursorStrategy<ScrollPosition> cursorStrategy;

    /**
     * @param postDetailPort       the community module's declared detail
     *                             port — both legs' owning seam (the same
     *                             use cases the REST detail and comments
     *                             reads serve)
     * @param currentUserProvider  resolves the authenticated principal into
     *                             the caller's id (the membership scope —
     *                             never a client parameter)
     * @param feedMapper           maps the shared post projection into the
     *                             generated transport type the detail leg
     *                             returns (the SAME mapper the feed leg
     *                             rides — the same-journey field set)
     * @param commentMapper        maps the shared comment projection into
     *                             this surface's generated transport types
     * @param properties           the typed {@code marketplace.graphql.*}
     *                             binding — the pagination bounds the
     *                             comments collection field resolves against
     * @param cursorStrategy       the connection-cursor codec — the SAME
     *                             Boot-auto-configured bean the services
     *                             and neighborhoodFeed fields ride (the
     *                             cursor wire format is the framework's
     *                             own)
     */
    public PostDetailDataFetcher(NeighborhoodPostDetailPort postDetailPort,
                                 CurrentUserProvider currentUserProvider,
                                 NeighborhoodFeedMapper feedMapper,
                                 PostCommentMapper commentMapper,
                                 GraphQlProperties properties,
                                 EncodingCursorStrategy<ScrollPosition> cursorStrategy) {
        this.postDetailPort = postDetailPort;
        this.currentUserProvider = currentUserProvider;
        this.feedMapper = feedMapper;
        this.commentMapper = commentMapper;
        this.properties = properties;
        this.cursorStrategy = cursorStrategy;
    }

    /**
     * The post detail leg — the caller's scope resolved through the
     * principal seam, the stored facts plus the caller-scoped reaction
     * facts plus the post's grouped media entries in ONE port answer
     * (the readiness doc §4.3-3). The id argument is NOT permission:
     * the owner re-validates the post's current state and the caller's
     * membership at open time (the honest 404/403 travel the seam as
     * the field-level denial the nullable envelope carries).
     * Selection-driven cost: this field runs only when the operation
     * document selects it.
     */
    @DgsQuery(field = DgsConstants.QUERY.Post)
    @RateLimiter(name = "graphqlPostQuery")
    public NeighborhoodPost post(@InputArgument UUID id) {
        NeighborhoodFeedPostView view = postDetailPort.post(currentCallerId(), id);
        return feedMapper.toTransport(view);
    }

    /**
     * The post detail journey's comments leg — the bounded page of the
     * post's comments on the owner's complete sort key, reached through
     * the SAME post gate first. The caller's scope through the principal
     * seam (the membership IS the scope — there is no location argument:
     * a client cannot ask for anyone else's neighborhood), the same
     * bounds contract the services and neighborhoodFeed fields
     * established (default when {@code first} is absent, clamped to the
     * configured hard maximum, a non-positive {@code first} answered as
     * the relay spec's honest empty page without touching the owner).
     *
     * <p>The page crosses the boundary as the framework-neutral
     * {@link PagedRequest} (the 2026-09-25 port-audit rule) and returns
     * as a {@link Page} so the framework's own connection adapter builds
     * the envelope — the mapping into the generated transport type stays
     * this surface's own duty. The owner's denials (the honest 404 for
     * an unknown/hidden/deleted post, the 403 for a non-member) travel
     * the seam — classified to the NF-001/AUTHZ taxonomies at the field
     * level by the exception resolver, resolving the nullable connection
     * to null with the classified error while the sibling detail field
     * still resolves (the partial-data contract the SDL documents).</p>
     */
    @DgsQuery(field = DgsConstants.QUERY.PostComments)
    @RateLimiter(name = "graphqlPostCommentsQuery")
    public Page<PostComment> postComments(@InputArgument UUID postId,
                                          @InputArgument Integer first,
                                          @InputArgument String after) {
        int requested = (first == null)
                ? properties.pagination().defaultPageSize()
                : first;
        if (requested <= 0) {
            // Relay connection spec: a non-positive `first` asks for an
            // empty page — answer it honestly without any owning-module
            // work (the services field's own measured behavior).
            return Page.empty();
        }
        int pageSize = Math.min(requested, properties.pagination().maxPageSize());
        int pageNumber = pageFor(after, pageSize);
        PagedRequest request = PagedRequest.of(pageNumber, pageSize);
        PagedResponse<NeighborhoodPostCommentView> page =
                postDetailPort.comments(currentCallerId(), postId, request);
        List<PostComment> content = page.content().stream()
                .map(commentMapper::toTransport)
                .toList();
        return new PageImpl<>(content,
                PageRequest.of(page.pageNumber(), page.pageSize()),
                page.totalElements());
    }

    /**
     * The authenticated principal's caller id — the membership scope both
     * owning legs consume. Resolved from the request thread's security
     * context (the DGS invocation model has no Authentication parameter
     * resolver — the measured pattern the home and mutation paths ride;
     * fetchers run synchronously on the servlet request thread).
     */
    private UUID currentCallerId() {
        Authentication authentication = SecurityContextHolder.getContext().getAuthentication();
        return currentUserProvider.getCurrentUserId(authentication);
    }

    /**
     * Derives the zero-based page index from the {@code after} cursor
     * string — the services field's own measured mechanics, verbatim:
     * the exclusive-after semantics (the item at {@code offset} is
     * excluded, so the page starts at {@code offset + 1}), page-aligned
     * cursors land exactly, a misaligned one is rejected as a
     * client-contract violation (VAL-001) rather than clamped (clamping
     * repeats or skips items — the overlap/gap ambiguity the connection
     * contract forbids), and an absent {@code after} is the first page.
     */
    private int pageFor(String after, int pageSize) {
        if (after == null) {
            return 0;
        }
        ScrollPosition position = cursorStrategy.fromCursor(after);
        return pageIndex(OffsetPosition.pageOf(position), pageSize);
    }

    /**
     * Converts a cursor offset into the zero-based page index — the
     * services field's own guard pair: an offset beyond the addressable
     * page space and a misaligned cursor (a client that changed
     * {@code first} between pages) are both rejected as validation
     * errors, never silently clamped.
     */
    private static int pageIndex(long offset, int pageSize) {
        long firstItem = offset + 1;
        if (firstItem > Integer.MAX_VALUE - pageSize) {
            throw new IllegalArgumentException(
                    "after cursor offset " + offset + " is outside the paginable range");
        }
        if (firstItem % pageSize != 0) {
            throw new IllegalArgumentException(
                    "after cursor offset " + offset + " is not aligned to the requested page size "
                            + pageSize + " — paginate with the same first, or start over without after");
        }
        return (int) (firstItem / pageSize);
    }

    /**
     * The offset a connection cursor carries — strictly the forward
     * {@code O_<offset>} shape this surface's adapter emits; a keyset
     * ({@code K_}) cursor is a foreign format for this field's contract
     * and is rejected as a validation error.
     */
    private static final class OffsetPosition {
        static long pageOf(ScrollPosition position) {
            if (position instanceof OffsetScrollPosition offsetPosition) {
                return offsetPosition.getOffset();
            }
            throw new IllegalArgumentException(
                    "this field paginates by offset cursors; a keyset cursor is not valid here");
        }
    }
}
