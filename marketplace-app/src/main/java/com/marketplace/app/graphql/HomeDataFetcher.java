import com.marketplace.app.graphql.generated.DgsConstants;
import com.marketplace.app.graphql.generated.types.DiscoveryRow;
import com.marketplace.app.graphql.generated.types.NeighborhoodPost;
import com.marketplace.community.spi.NeighborhoodFeedPort;
import com.marketplace.discovery.spi.DiscoverySpi;
import com.marketplace.shared.api.NeighborhoodFeedPostView;
import com.marketplace.shared.api.PagedRequest;
import com.marketplace.shared.api.PagedResponse;
import com.marketplace.shared.security.CurrentUserProvider;
import com.netflix.graphql.dgs.DgsComponent;
import com.netflix.graphql.dgs.DgsQuery;
import com.netflix.graphql.dgs.InputArgument;
import io.github.resilience4j.ratelimiter.annotation.RateLimiter;
import org.springframework.data.domain.OffsetScrollPosition;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.ScrollPosition;
import org.springframework.graphql.data.pagination.EncodingCursorStrategy;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;

import java.util.List;
import java.util.UUID;

/**
 * The first composite user journey's GraphQL adapter (the corrected
 * plan §11-Phase-6 + the journey inventory #599 §7 stage 4: «قراءة
 * مركبة للاكتشاف/موجز الحي»). The journey-aware composition role the
 * GraphQL target design assigns this surface (design §1: compose
 * experiences, never mirror the database or duplicate business rules)
 * — its first real journey: the home read.
 *
 * <p><b>The composite lives in the OPERATION DOCUMENT, not in a
 * wrapper type:</b> the two root fields the home journey composes in
 * ONE authenticated round-trip (the measured REST comparison the
 * inventory's acceptance gate pins — the same journey over REST is two
 * HTTP requests: {@code GET /api/v1/discovery} +
 * {@code GET /api/v1/neighborhood/posts}). GraphQL composes at the
 * document level: the client selects both root fields in one operation
 * and pays ONE transport round-trip while each field still delegates
 * to exactly its owning module's declared SPI — selection-driven cost
 * (a discovery-only document never touches the feed seam, and vice
 * versa — the cost tests pin this). A wrapper type would add nothing
 * the document does not already carry, and a generated wrapper type
 * holding a {@code *Connection} field would reference a type no
 * build-time generator emits (the connection types are
 * runtime-generated by {@code ConnectionTypeDefinitionConfigurer} —
 * the Phase-1 design; measured from the graphql-dgs-codegen 8.6.0
 * source, the Query root is excluded from data-type generation, so
 * root fields compose without that artifact).</p>
 *
 * <p><b>One use case, one set of rules — on both legs</b> (the
 * inventory §8: «يجب أن يستدعي REST وGraphQL Use Case واحدًا وقواعد
 * عمل واحدة»): the discovery leg delegates to the discovery module's
 * declared {@link DiscoverySpi} (the same {@code homeRows} use case
 * the REST home endpoint serves — the §1.4 rail order, the per-rail
 * bound, the no-empty-rail omission and the membership scope all stay
 * inside the owner); the feed leg delegates to the community module's
 * declared {@link NeighborhoodFeedPort} (the same {@code getFeed} use
 * case the REST feed serves — the membership gate, the visibility
 * floor and the complete sort key {@code createdAt DESC, id DESC}
 * stay inside the owner). This adapter owns ZERO domain rules; its
 * only work is identity resolution, the bounded pagination math, and
 * the mapping into the SDL's own generated transport types.</p>
 *
 * <p><b>The field-level denial contract:</b> the discovery field
 * answers the honest empty list for a membership-less caller (the
 * owner's own rule), while the feed field answers the REST feed's own
 * explicit denial — the {@code AccessDeniedException} the owner throws
 * travels the seam and the exception resolver classifies it to the
 * AUTHZ taxonomy AT THE FIELD LEVEL. The SDL declares the feed's
 * connection NULLABLE deliberately (unlike {@code services}): on a
 * non-null ROOT field a GraphQL field error propagates the null up to
 * the root and destroys the whole composite's data (discovery included
 * — measured against the GraphQL spec's null propagation; strictly
 * worse than the REST journey it replaces), so the nullable envelope
 * carries the denial the honest way — the field resolves to null WITH
 * one AUTHZ-classified error in {@code errors[]}, while discovery
 * still resolves its honest empty list. The composite never bends
 * either owner's rules and never destroys the sibling section.</p>
 *
 * <p><b>Programming model:</b> DGS — {@code @DgsComponent} +
 * {@code @DgsQuery}/{@code @InputArgument} with the schema-first
 * {@code DgsConstants} field bindings (the Phase-2/3 pattern the
 * {@code ServiceDataFetcher} established; an SDL rename or removal
 * fails compilation HERE instead of drifting). The feed connection
 * rides the SAME official pagination path the services field measured
 * end to end: the relay {@code first}/{@code after} arguments bind
 * onto this method, the cursor decodes through the injected
 * Boot-configured {@code EncodingCursorStrategy}
 * ({@code ScrollPositionCursorStrategy}, base64), the bounded page
 * crosses the framework-neutral port as a {@link PagedRequest}, and
 * the returned {@link Page} is adapted into the
 * {@code NeighborhoodPostConnection} envelope by Boot's
 * {@code ConnectionFieldTypeVisitor} through the DGS integration's
 * customizer chain — identical envelope, identical
 * {@code O_<offset>} cursors on the wire, identical bounds logic
 * (default-when-absent, hard-capped, non-positive {@code first} =
 * the relay spec's honest empty page without any repository work,
 * misaligned or foreign cursors rejected as validation errors).</p>
 *
 * <p><b>The principal:</b> resolved from the request thread's
 * {@link SecurityContextHolder} — the DGS method-invocation model has
 * no {@code Authentication} parameter resolver (measured: no such
 * argument resolver in dgs-framework 12.1.0), and the integration runs
 * data fetchers synchronously on the servlet request thread — the same
 * measured pattern the mutation path rides. The endpoint itself sits
 * behind the resource-server chain's {@code anyRequest().authenticated()}
 * (anonymous never reaches this adapter; the security integration test
 * pins the 401).</p>
 */
@DgsComponent
public class HomeDataFetcher {

    private final DiscoverySpi discoverySpi;
    private final NeighborhoodFeedPort feedPort;
    private final CurrentUserProvider currentUserProvider;
    private final DiscoveryMapper discoveryMapper;
    private final NeighborhoodFeedMapper feedMapper;
    private final GraphQlProperties properties;
    private final EncodingCursorStrategy<ScrollPosition> cursorStrategy;

    /**
     * @param discoverySpi         the discovery module's declared SPI — the
     *                             home rails' owning seam (the same use
     *                             case the REST home endpoint serves)
     * @param feedPort             the community module's declared feed
     *                             port — the feed page's owning seam (the
     *                             same use case the REST feed serves)
     * @param currentUserProvider  resolves the authenticated principal into
     *                             the caller's id (the membership scope —
     *                             never a client parameter)
     * @param discoveryMapper      maps the discovery projection into this
     *                             surface's generated transport types
     * @param feedMapper           maps the shared feed projection into this
     *                             surface's generated transport types
     * @param properties           the typed {@code marketplace.graphql.*}
     *                             binding — the pagination bounds every
     *                             collection field resolves against
     * @param cursorStrategy       the connection-cursor codec — the SAME
     *                             Boot-auto-configured bean the services
     *                             field rides (the cursor wire format is
     *                             the framework's own)
     */
    public HomeDataFetcher(DiscoverySpi discoverySpi,
                           NeighborhoodFeedPort feedPort,
                           CurrentUserProvider currentUserProvider,
                           DiscoveryMapper discoveryMapper,
                           NeighborhoodFeedMapper feedMapper,
                           GraphQlProperties properties,
                           EncodingCursorStrategy<ScrollPosition> cursorStrategy) {
        this.discoverySpi = discoverySpi;
        this.feedPort = feedPort;
        this.currentUserProvider = currentUserProvider;
        this.discoveryMapper = discoveryMapper;
        this.feedMapper = feedMapper;
        this.properties = properties;
        this.cursorStrategy = cursorStrategy;
    }

    /**
     * The home discovery rails — the caller's scope resolved through the
     * principal seam, the assembly fully owned by the discovery module
     * (the §1.4 rail order, the per-rail card bound, the no-empty-rail
     * omission, the honest empty list for a membership-less caller).
     * Selection-driven cost: this field runs only when the operation
     * document selects it.
     */
    @DgsQuery(field = DgsConstants.QUERY.Discovery)
    @RateLimiter(name = "graphqlDiscoveryQuery")
    public List<DiscoveryRow> discovery() {
        UUID callerId = currentCallerId();
        return discoverySpi.homeRows(callerId).stream()
                .map(discoveryMapper::toTransport)
                .toList();
    }

    /**
     * The neighborhood live feed's bounded page — the caller's scope
     * through the principal seam (there is no location argument: the
     * membership IS the scope, G-N1/G-N3 — a client cannot ask for
     * anyone else's feed), the owner's complete sort key, the same
     * bounds contract the services field established (default when
     * {@code first} is absent, clamped to the configured hard maximum, a
     * non-positive {@code first} answered as the relay spec's honest
     * empty page without touching the owner).
     *
     * <p>The page crosses the boundary as the framework-neutral
     * {@link PagedRequest} (the 2026-09-25 port-audit rule) and returns
     * as a {@link Page} so the framework's own connection adapter builds
     * the envelope — the mapping into the generated transport type stays
     * this surface's own duty. A membership-less caller answers the
     * owner's {@code AccessDeniedException} — classified to the AUTHZ
     * taxonomy at the field level by the exception resolver, resolving
     * the nullable connection to null with the classified error while
     * the sibling discovery field still resolves (the partial-data
     * contract the SDL documents).</p>
     */
    @DgsQuery(field = DgsConstants.QUERY.NeighborhoodFeed)
    @RateLimiter(name = "graphqlNeighborhoodFeedQuery")
    public Page<NeighborhoodPost> neighborhoodFeed(@InputArgument Integer first,
                                                   @InputArgument String after) {
        int requested = (first == null)
                ? properties.pagination().defaultPageSize()
                : first;
        if (requested <= 0) {
            // Relay connection spec: a non-positive `first` asks for an
            // empty page — answer it honestly without any owning-module
            // work (the services field's own measured behavior).
            return Page.empty();
        }
        int pageSize = Math.min(requested, properties.pagination().maxPageSize());
        int pageNumber = pageFor(after, pageSize);
        PagedRequest request = PagedRequest.of(pageNumber, pageSize);
        PagedResponse<NeighborhoodFeedPostView> page = feedPort.feed(currentCallerId(), request);
        List<NeighborhoodPost> content = page.content().stream()
                .map(feedMapper::toTransport)
                .toList();
        return new PageImpl<>(content,
                PageRequest.of(page.pageNumber(), page.pageSize()),
                page.totalElements());
    }

    /**
     * The authenticated principal's caller id — the membership scope both
     * owning seams consume. Resolved from the request thread's security
     * context (the DGS invocation model has no Authentication parameter
     * resolver — the measured pattern the mutation path rides; fetchers
     * run synchronously on the servlet request thread).
     */
    private UUID currentCallerId() {
        Authentication authentication = SecurityContextHolder.getContext().getAuthentication();
        return currentUserProvider.getCurrentUserId(authentication);
    }

    /**
     * Derives the zero-based page index from the {@code after} cursor
     * string — the services field's own measured mechanics, verbatim:
     * the exclusive-after semantics (the item at {@code offset} is
     * excluded, so the page starts at {@code offset + 1}), page-aligned
     * cursors land exactly, a misaligned one is rejected as a
     * client-contract violation (VAL-001) rather than clamped (clamping
     * repeats or skips items — the overlap/gap ambiguity the connection
     * contract forbids), and an absent {@code after} is the first page.
     */
    private int pageFor(String after, int pageSize) {
        if (after == null) {
            return 0;
        }
        ScrollPosition position = cursorStrategy.fromCursor(after);
        return pageIndex(OffsetPosition.pageOf(position), pageSize);
    }

    /**
     * Converts a cursor offset into the zero-based page index — the
     * services field's own guard pair: an offset beyond the addressable
     * page space and a misaligned cursor (a client that changed
     * {@code first} between pages) are both rejected as validation
     * errors, never silently clamped.
     */
    private static int pageIndex(long offset, int pageSize) {
        long firstItem = offset + 1;
        if (firstItem > Integer.MAX_VALUE - pageSize) {
            throw new IllegalArgumentException(
                    "after cursor offset " + offset + " is outside the paginable range");
        }
        if (firstItem % pageSize != 0) {
            throw new IllegalArgumentException(
                    "after cursor offset " + offset + " is not aligned to the requested page size "
                            + pageSize + " — paginate with the same first, or start over without after");
        }
        return (int) (firstItem / pageSize);
    }

    /**
     * The offset a connection cursor carries — strictly the forward
     * {@code O_<offset>} shape this surface's adapter emits; a keyset
     * ({@code K_}) cursor is a foreign format for this field's contract
     * and is rejected as a validation error.
     */
    private static final class OffsetPosition {
        static long pageOf(ScrollPosition position) {
            if (position instanceof OffsetScrollPosition offsetPosition) {
                return offsetPosition.getOffset();
            }
            throw new IllegalArgumentException(
                    "this field paginates by offset cursors; a keyset cursor is not valid here");
        }
    }
}
