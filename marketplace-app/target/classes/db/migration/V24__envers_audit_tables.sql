-- Foreign keys for all _aud tables referencing revinfo
-- PostgreSQL can validate FK in one ALTER TABLE per constraint
-- (omitting CASCADE since revinfo rows are never deleted)
do $$
declare
    tbl text;
begin
    foreach tbl in array array[
        'users_aud', 'provider_listings_aud', 'bookings_aud',
        'payments_aud', 'payment_intents_aud', 'payment_webhook_events_aud',
        'pricing_rules_aud', 'reviews_aud', 'messages_aud', 'conversations_aud',
        'provider_profiles_aud', 'availability_slots_aud',
        'provider_availability_rules_aud', 'provider_time_off_aud',
        'notifications_aud', 'ledger_entries_aud', 'provider_balances_aud',
        'disputes_aud'
    ] loop
        execute format(
            'alter table %I add constraint fk_%s_revinfo foreign key (rev) references revinfo (rev)',
            tbl, replace(tbl, '_aud', '')
        );
    end loop;
end;
$$;

