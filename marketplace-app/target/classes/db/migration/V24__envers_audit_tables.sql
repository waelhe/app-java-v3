-- Hibernate Envers audit tables
-- Required for @Audited entities with spring.jpa.hibernate.ddl-auto=none
-- Each _aud table stores historical snapshots of entity revisions.
-- REVTYPE: 0 = ADD, 1 = MOD, 2 = DEL

create table if not exists revinfo (
    rev      integer generated by default as identity primary key,
    revtstmp bigint
);

